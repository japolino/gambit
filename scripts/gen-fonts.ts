/**
 * Embeds the display fonts the scene themes use (latin woff2, base64) into
 * src/frontend/scene/fonts.ts: @font-face is ignored inside a shadow root,
 * so the host declares them on the page. All SIL Open Font License 1.1,
 * see licenses/. Run: bun scripts/gen-fonts.ts
 */
import { readFileSync, writeFileSync, copyFileSync, existsSync } from "node:fs";
import { join } from "node:path";
const root = join(import.meta.dir, "..");
const F: [family: string, pkg: string, file: string, weight: number, style: string][] = [
  ["Gambit Cinzel", "cinzel", "cinzel-latin-600-normal", 600, "normal"],
  ["Gambit Cinzel", "cinzel", "cinzel-latin-800-normal", 800, "normal"],
  ["Gambit Fell", "im-fell-english", "im-fell-english-latin-400-normal", 400, "normal"],
  ["Gambit Fell", "im-fell-english", "im-fell-english-latin-400-italic", 400, "italic"],
  ["Gambit 8bit", "press-start-2p", "press-start-2p-latin-400-normal", 400, "normal"],
  ["Gambit Garamond", "cormorant-garamond", "cormorant-garamond-latin-500-normal", 500, "normal"],
  ["Gambit Garamond", "cormorant-garamond", "cormorant-garamond-latin-700-normal", 700, "normal"],
  ["Gambit Garamond", "cormorant-garamond", "cormorant-garamond-latin-500-italic", 500, "italic"],
];
const css = F.map(([fam, pkg, file, w, st]) => {
  const b64 = readFileSync(join(root, "node_modules/@fontsource", pkg, "files", `${file}.woff2`)).toString("base64");
  return `@font-face { font-family: "${fam}"; font-weight: ${w}; font-style: ${st}; font-display: block; src: url(data:font/woff2;base64,${b64}) format("woff2"); }`;
}).join("\n");
for (const pkg of new Set(F.map((f) => f[1]))) {
  const lic = join(root, "node_modules/@fontsource", pkg, "LICENSE");
  if (existsSync(lic)) copyFileSync(lic, join(root, "licenses", `${pkg}-OFL.txt`));
}
writeFileSync(join(root, "src/frontend/scene/fonts.ts"), `/**\n * Display fonts for the scene themes (generated by scripts/gen-fonts.ts from\n * @fontsource; SIL Open Font License 1.1, see licenses/). Families:\n * "Gambit Cinzel" 600/800, "Gambit Fell" 400 + italic,\n * "Gambit 8bit" (8x8 pixel), "Gambit Garamond" 500/700 + italic.\n * The pixel font "Gambit Pixel" (VT323) lives in pixel-font.ts.\n */\nexport const THEME_FONTS_CSS = ${JSON.stringify(css)};\n`);
console.log("fonts.ts", Math.round(css.length / 1024), "KB");
